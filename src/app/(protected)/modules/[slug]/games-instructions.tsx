function ScoresInstructions() {
  return (
    <>
      <p className="text-sm text-muted">
        Every finished game, best first. The board is deliberately{" "}
        <strong className="text-ink">shared</strong> rather than per-person: it answers
        &ldquo;who is best at this&rdquo;, so you see everyone&rsquo;s results and they see
        yours.
      </p>
      <Section title="Reading the board">
        <ul className="flex list-disc flex-col gap-1 pl-5">
          <li>Ties are broken in favour of whoever got there first.</li>
          <li>
            A score is never edited or removed — a finished game is a historical fact. It also
            survives the account that set it being deleted, showing as{" "}
            <em>Unknown player</em> rather than vanishing.
          </li>
        </ul>
      </Section>
    </>
  );
}

function ConfigurationInstructions() {
  return (
    <>
      <p className="text-sm text-muted">
        There is nothing to configure yet. The list of games is part of the application
        rather than something stored, so a game appears here when it has been built — it
        cannot be added or removed from a screen.
      </p>
      <Section title="Why the game list isn't editable">
        <p>
          A game only exists if the code that draws it does. A row in a table naming a game
          this version cannot run would produce a card that goes nowhere, so the catalogue
          lives in the code beside the games themselves.
        </p>
      </Section>
    </>
  );
}

export function GamesInstructions({ section }: { section: GamesSection }) {
  if (section === "scores") return <ScoresInstructions />;
  if (section === "configuration") return <ConfigurationInstructions />;
  return <ArcadeInstructions />;
}
